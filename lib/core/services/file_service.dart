import 'dart:io';

import 'package:file_picker/file_picker.dart';
import 'package:get/get.dart';
import 'package:image_picker/image_picker.dart';
import 'package:open_filex/open_filex.dart';
import 'package:path/path.dart' as p;
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';

class StoredFile {
  StoredFile(this.path, this.name, this.size);
  final String path;
  final String name;
  final int size;
}

/// Local attachment storage. Files are always copied into the app's own
/// documents directory so they survive when the picker's temp file is removed.
class FileService extends GetxService {
  Future<Directory> _dir(String sub) async {
    final base = await getApplicationDocumentsDirectory();
    final d = Directory(p.join(base.path, sub));
    if (!await d.exists()) await d.create(recursive: true);
    return d;
  }

  Future<StoredFile?> _store(String srcPath, String origName) async {
    final dir = await _dir('attachments');
    final safe = origName.replaceAll(RegExp(r'[^\w.\-؀-ۿ ]'), '_');
    final target =
        p.join(dir.path, '${DateTime.now().millisecondsSinceEpoch}_$safe');
    final copied = await File(srcPath).copy(target);
    return StoredFile(copied.path, origName, await copied.length());
  }

  /// Opens the system file picker. Returns null if cancelled or failed.
  Future<List<StoredFile>> pickFiles() async {
    try {
      final r = await FilePicker.platform.pickFiles(allowMultiple: true);
      if (r == null) return [];
      final out = <StoredFile>[];
      for (final f in r.files) {
        if (f.path == null) continue;
        final s = await _store(f.path!, f.name);
        if (s != null) out.add(s);
      }
      return out;
    } catch (_) {
      return [];
    }
  }

  Future<StoredFile?> pickImage({bool camera = false}) async {
    try {
      final x = await ImagePicker().pickImage(
        source: camera ? ImageSource.camera : ImageSource.gallery,
        imageQuality: 85,
      );
      if (x == null) return null;
      return _store(x.path, x.name);
    } catch (_) {
      return null;
    }
  }

  /// Saves generated bytes (e.g. PDF) into the app's documents folder.
  Future<File> saveBytes(String sub, String fileName, List<int> bytes) async {
    final dir = await _dir(sub);
    final f = File(p.join(dir.path, fileName));
    return f.writeAsBytes(bytes, flush: true);
  }

  Future<bool> exists(String? path) async =>
      path != null && path.isNotEmpty && await File(path).exists();

  /// Returns an error key ('file_missing' / 'file_open_failed') or null.
  Future<String?> open(String? path) async {
    if (!await exists(path)) return 'file_missing';
    try {
      final r = await OpenFilex.open(path!);
      return r.type == ResultType.done ? null : 'file_open_failed';
    } catch (_) {
      return 'file_open_failed';
    }
  }

  Future<String?> share(String? path) async {
    if (!await exists(path)) return 'file_missing';
    try {
      await Share.shareXFiles([XFile(path!)]);
      return null;
    } catch (_) {
      return 'file_open_failed';
    }
  }

  Future<void> deleteFile(String? path) async {
    try {
      if (await exists(path)) await File(path!).delete();
    } catch (_) {}
  }
}
